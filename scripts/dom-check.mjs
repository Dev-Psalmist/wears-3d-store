import { chromium } from 'playwright-core'
const B='https://wears-3d-store.vercel.app'
const b=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']})
const p=await b.newPage({viewport:{width:1440,height:900}})
await p.goto(B+'/',{waitUntil:'load'}); await p.waitForTimeout(3500)
const head=await p.locator('h1').first().innerText()
const nav=await p.locator('header').first().innerText()
console.log('H1:', JSON.stringify(head))
console.log('NAV:', JSON.stringify(nav.replace(/\n/g,' | ').slice(0,140)))
const foot=await p.locator('footer').first().innerText()
console.log('FOOTER has line:', /Explore the collection/.test(foot))
await p.goto(B+'/product/halo-02',{waitUntil:'load'}); await p.waitForTimeout(3500)
const body=await p.locator('body').innerText()
for (const [label,re] of [['COLLECTION back',/collection/i],['code',/HALO 02/],['price',/\$\s?\d/],['size',/select a size/i],['add to bag',/add to bag/i],['description',/\./]])
  console.log(label+':', re.test(body))
const links=await p.locator('a').count()
console.log('links on detail:',links)
await p.screenshot({path:'/tmp/live-shots/detail-halo.png'})
await p.goto(B+'/',{waitUntil:'load'}); await p.waitForTimeout(3500); await p.screenshot({path:'/tmp/live-shots/home-full.png', fullPage:true})
await b.close()
