import { chromium } from 'playwright-core'
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'] })
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } })
await p.goto('https://wears-3d-store.vercel.app/', { waitUntil: 'load' })
await p.waitForTimeout(4000)
console.log('scrollY0', await p.evaluate(() => window.scrollY), 'docH', await p.evaluate(() => document.documentElement.scrollHeight))
await p.evaluate(() => window.scrollTo(0, 900))
await p.waitForTimeout(2000)
console.log('scrollY1', await p.evaluate(() => window.scrollY))
const box = await p.locator('[data-testid="product-tile"]').nth(2).boundingBox()
console.log('tile2 box', JSON.stringify(box))
await p.screenshot({ path: 'docs/grid.png' })
await b.close()
